def read_index(root):
    path = rpath(root, INDEX_REL)
    if not os.path.isfile(path):
        return None
    try:
        return read_text(path)
    except (OSError, UnicodeDecodeError):
        return None


def write_index(root, memories=None):
    """Regenerate MEMORY.md; return True when the file changed."""
    if memories is None:
        memories, _ = scan_store(root)
    text = render_index(memories)
    if read_index(root) == text:
        return False
    write_text(rpath(root, INDEX_REL), text)
    return True


def is_union_line(line):
    """True for the chronicle union line, also written root-anchored (`/docs/memory/...`)."""
    return " ".join(line.split()).lstrip("/") == UNION_LINE


def ensure_union_line(root):
    path = rpath(root, ".gitattributes")
    text = ""
    if os.path.lexists(path):
        if not os.path.isfile(path):
            raise ChronicleError("%s is not a regular file: add `%s` to it by hand" % (path, UNION_LINE))
        try:
            with open(path, encoding="utf-8", newline="") as f:
                text = f.read()
        except UnicodeDecodeError:
            raise ChronicleError("%s is not UTF-8 (git reads it as UTF-8; PowerShell 5.1 `>` writes UTF-16): "
                                 "re-save it as UTF-8; left unchanged" % path)
        except OSError as e:
            raise ChronicleError("cannot read %s (%s)" % (path, e.strerror or e))
    eol = "\r\n" if "\r\n" in text else "\n"
    out, seen, dropped = [], False, 0
    for line in text.splitlines(True):
        if is_union_line(line):
            if seen:
                dropped += 1
                continue
            seen = True
        out.append(line)
    if not seen:
        if out and not out[-1].endswith(("\n", "\r")):
            out[-1] += eol
        out.append(UNION_LINE + eol)
    new = "".join(out)
    if new == text:
        return None
    try:
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(new)
    except OSError as e:
        raise ChronicleError("cannot write %s (%s)" % (path, e.strerror or e))
    if dropped:
        return "removed %d duplicate `%s` line(s) from .gitattributes" % (dropped, UNION_LINE)
    return "added `%s` to .gitattributes" % UNION_LINE


def ensure_store(root):
    actions = []
    memdir = rpath(root, MEMORY_REL)
    if not os.path.isdir(memdir):
        os.makedirs(memdir)
        actions.append("created %s/" % MEMORY_REL)
    if write_index(root):
        actions.append("wrote %s" % INDEX_REL)
    changed = ensure_union_line(root)
    if changed:
        actions.append(changed)
    return actions


def legacy_present(root):
    found = []
    for rel in LEGACY_FILES:
        full = rpath(root, rel)
        if os.path.isfile(full):
            try:
                size = human_size(os.path.getsize(full))
            except OSError:
                size = "?"
            found.append((rel, size))
    for rel in LEGACY_DIRS:
        full = rpath(root, rel)
        if os.path.isdir(full):
            try:
                n = len(os.listdir(full))
            except OSError:
                n = 0
            found.append((rel + "/", "%d files" % n))
    return found


