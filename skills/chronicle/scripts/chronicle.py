    for title, items in sections:
        lines += ["", title] + ["  " + item for item in (items or ["none"])]
    lines += ["", "Checklist (procedure: references/migrate.md in the chronicle skill)"]
    lines += ["  [ ] %d. %s" % (i, step) for i, step in enumerate(steps, 1)]
    note = _hooks_path_note(root, use_git, layout[2])
    if note:
        lines.append("  note: " + note)
    return lines


