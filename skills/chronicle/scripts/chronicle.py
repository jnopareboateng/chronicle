def cmd_index(args):
    root = repo_root(args.cwd)
    if not os.path.isdir(rpath(root, MEMORY_REL)):
        raise ChronicleError("%s does not exist (run chronicle init)" % MEMORY_REL)
    memories, _ = scan_store(root)
    for m in memories:
        if not m.indexable:
            print("skipped %s: %s (see chronicle lint)" % (m.rel, m.error or "invalid type"), file=sys.stderr)
    expected = render_index(memories)
    n = count_entries(expected)
    if args.check:
        if read_index(root) != expected:
            print("%s is out of date (run chronicle index)" % INDEX_REL)
            return 1
        print("%s is up to date (%d entries)" % (INDEX_REL, n))
        return 0
    changed = write_index(root, memories)
    print("%s %s (%d entries)" % ("wrote" if changed else "unchanged:", INDEX_REL, n))
    return 0


def cmd_lint(args):
    root = repo_root(args.cwd)
    findings, n = lint_store(root)
    for level, path, msg in findings:
        print("%s %s: %s" % (level, path, msg))
    errors = sum(1 for f in findings if f[0] == "ERROR")
    warnings = len(findings) - errors
    print("chronicle lint: %d memories, %d errors, %d warnings" % (n, errors, warnings), file=sys.stderr)
    return 1 if errors or (args.strict and warnings) else 0


def cmd_new(args):
    root = repo_root(args.cwd)
    slug = args.slug
    description = " ".join(args.description.split())
    if not NAME_RE.match(slug):
        raise ChronicleError("invalid slug `%s`: use 3-64 chars of a-z, 0-9 and -, starting with a letter or digit" % slug)
    if args.type == "status" and not slug.startswith("status-"):
        raise ChronicleError("status entries must be named status-<branch or topic>, e.g. status-%s" % slug)
    if not description:
        raise ChronicleError("--description must not be empty")
    if len(description) > DESCRIPTION_MAX:
        print("warning: description is %d chars (budget %d)" % (len(description), DESCRIPTION_MAX), file=sys.stderr)
    path = rpath(root, MEMORY_REL + "/" + slug + ".md")
    if os.path.exists(path):
        raise ChronicleError("%s/%s.md already exists: update it instead" % (MEMORY_REL, slug))
    for action in ensure_store(root):
        print(action, file=sys.stderr)
    content = "---\nname: %s\ndescription: %s\ntype: %s\nupdated: %s\n---\n%s" % (
        slug, yaml_scalar(description), args.type, today().isoformat(), BODY_TEMPLATE)
    try:
        with open(path, "x", encoding="utf-8", newline="\n") as f:
            f.write(content)
    except FileExistsError:
        raise ChronicleError("%s/%s.md already exists: update it instead" % (MEMORY_REL, slug))
    write_index(root)
    print(path)
    return 0


