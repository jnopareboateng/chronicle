def build_parser():
    import argparse

    ap = argparse.ArgumentParser(prog="chronicle", description="Shared project memory in docs/memory (see SKILL.md).")
    sub = ap.add_subparsers(dest="command", metavar="command")
    sub.required = True

    def add(name, text, func):
        sp = sub.add_parser(name, help=text, description=text)
        sp.add_argument("--cwd", default=".", help="a directory inside the target repo (default: .)")
        sp.set_defaults(func=func)
        return sp

    sp = add("context", "print the memory index for a SessionStart hook (never fails)", cmd_context)
    sp.add_argument("--max-bytes", type=int, default=CONTEXT_MAX_BYTES,
                    help="output budget in bytes (default %d, minimum %d)" % (CONTEXT_MAX_BYTES, CONTEXT_MIN_BYTES))
    sp = add("index", "regenerate docs/memory/MEMORY.md", cmd_index)
    sp.add_argument("--check", action="store_true", help="write nothing; exit 1 if out of date")
    sp = add("lint", "validate the memory store", cmd_lint)
    sp.add_argument("--strict", action="store_true", help="fail on warnings too")
    sp = add("new", "scaffold a memory file and reindex", cmd_new)
    sp.add_argument("type", choices=TYPES)
    sp.add_argument("slug")
    sp.add_argument("--description", "-d", required=True)
    add("init", "create docs/memory, MEMORY.md and the .gitattributes union line", cmd_init)
    add("migrate-plan", "read-only inventory and checklist for legacy memory", cmd_migrate_plan)
    sp = add("install", "copy this skill to ~/.claude and/or ~/.codex; optional SessionStart hooks", cmd_install)
    sp.add_argument("--claude", action="store_true", help="install for Claude Code")
