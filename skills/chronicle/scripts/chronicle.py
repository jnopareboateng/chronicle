def _nbytes(line):
    """Output size of one line: UTF-8 plus its LF (stdout is reconfigured to LF everywhere)."""
    return len(line.encode("utf-8")) + 1


def _compact(groups):
    """Names-only lines for [(section, [names])]: one heading per section, then the names
    comma-separated and wrapped. A wrap turns ", " into ",\\n", so wrapping never changes the
    byte count _fit plans with: heading line + names + 2 bytes per name after the first + LF."""
    out = []
    for section, names in groups:
        out.append(COMPACT_HEADING % section)
        line = ""
        for i, name in enumerate(names):
            piece = name + ("," if i + 1 < len(names) else "")
            if line and len(line) + 1 + len(piece) > COMPACT_WIDTH:
                out.append(line)
                line = piece
            else:
                line = line + " " + piece if line else piece
        out.append(line)
    return out


def _group(rows):
    """[(section, [names])] for the entry rows, one group per heading run."""
    groups = []
    for gid, title, name in rows:
        if name is None:
            continue
        if not groups or groups[-1][0] != gid:
            groups.append((gid, title, []))
        groups[-1][2].append(name)
    return [(title, names) for _, title, names in groups]


def _fit(head, body, max_bytes):
    """head + body within max_bytes, never dropping an entry without its name.

    Full lines go first, in index order, while the names of everything after them still fit.
    From the first line that would break that, the rest is names only, per section. Only when
    even the names overflow does the output end with a count of the entries left out.
    """
    used = sum(_nbytes(line) for line in head)
    if used + sum(_nbytes(line) for line in body) <= max_bytes:
        return head + body
    rows, gid, title = [], 0, "Other"  # per line: (heading run, section title, entry name or None)
    for line in body:
        name = None
        if line.startswith("## "):
            gid, title = gid + 1, line[3:].strip() or "Other"
        else:
            m = ENTRY_LINE_RE.match(line)
            if m and m.group(1):
                name = m.group(1)[:-3] if m.group(1).endswith(".md") else m.group(1)
        rows.append((gid, title, name))
    note = "... (more lines in %s)" % INDEX_REL
    n = len(body)
    # tail[i]: bytes of body[i:] in compact form; other[i]: body[i:] holds a line that is neither
    # heading nor entry (compact form drops it, so the note is added).
    tail, other = [0] * (n + 1), [False] * (n + 1)
    later, cur, cur_bytes = 0, None, 0
    for i in range(n - 1, -1, -1):
        g, t, name = rows[i]
        if name is not None:
            if g != cur:
                later, cur, cur_bytes = later + cur_bytes, g, _nbytes(COMPACT_HEADING % t) - 1
            cur_bytes += len(name.encode("utf-8")) + 2
        other[i] = other[i + 1] or (name is None and not body[i].startswith("## "))
        tail[i] = later + cur_bytes + (_nbytes(note) if other[i] else 0)
    if used + tail[0] <= max_bytes:
        taken = 0
        while taken < n and used + _nbytes(body[taken]) + tail[taken + 1] <= max_bytes:
            used += _nbytes(body[taken])
            taken += 1
        full = body[:taken]
        while full and full[-1].startswith("## "):  # a heading whose entries all went compact
            full.pop()
        return head + full + _compact(_group(rows[taken:])) + ([note] if other[taken] else [])
    total = sum(1 for row in rows if row[2] is not None)
    budget = max_bytes - used - _nbytes("... %d more in %s" % (total, INDEX_REL))
    shown, spent, last = [], 0, None
    for row in rows:
        if row[2] is None:
            continue
        cost = len(row[2].encode("utf-8")) + (2 if row[0] == last else _nbytes(COMPACT_HEADING % row[1]) + 1)
        if spent + cost > budget:
            break
        shown.append(row)
        spent, last = spent + cost, row[0]
    return head + _compact(_group(shown)) + ["... %d more in %s" % (total - len(shown), INDEX_REL)]


# The generated header comment: after only the `# ` title and blank lines, it starts with the
# generated marker and closes before any entry line or section heading.
_HEADER_COMMENT_RE = re.compile(
    r"\A(﻿?(?:[ \t]*(?:#[ \t][^\n]*)?\n)*)[ \t]*<!-- Generated by chronicle(?:(?!\n- \[|\n## ).)*?-->", re.S)


def strip_header_comment(text):
    """Remove the generated header comment only; any other comment, and every entry, is kept.

    Entry descriptions may themselves contain `<!--` or `-->`; they are never touched.
    """
    return _HEADER_COMMENT_RE.sub(r"\1", text, count=1)


def context_text(root, max_bytes=CONTEXT_MAX_BYTES):
    max_bytes = max(max_bytes, CONTEXT_MIN_BYTES)
    legacy = legacy_present(root)
    index_path = rpath(root, INDEX_REL)
    if os.path.isfile(index_path):
        with open(index_path, "rb") as f:
            raw = f.read(INDEX_READ_MAX + 1)
        head = [CONTEXT_HEADER]
        if legacy:
            head.append(
                "Legacy memory files still present (%s): do not bulk-read them; finish the "
                "migration per the chronicle skill." % ", ".join(rel for rel, _ in legacy)
            )
        if len(raw) > INDEX_READ_MAX:
            raw = raw[:INDEX_READ_MAX]
            head.append("(%s is over %d bytes: entries past that point are not shown; run chronicle lint)"
                        % (INDEX_REL, INDEX_READ_MAX))
        if b"\x00" in raw:
            return "\n".join(head + ["(%s is unreadable; run chronicle lint)" % INDEX_REL]) + "\n"
        text = strip_header_comment(raw.decode("utf-8", "replace").replace("\r\n", "\n"))
        body = [
            line.rstrip()
            for line in text.split("\n")
            if line.strip() and not re.match(r"^#\s+Project memory\s*$", line)
        ]
        if not body:
            body = ["(no entries yet)"]
        return "\n".join(_fit(head, body, max_bytes)) + "\n"
    if legacy:
        listing = ", ".join("%s (%s)" % item for item in legacy)
        return (
            "Legacy project memory (not yet migrated to chronicle docs/memory entries): %s.\n"
            "Do NOT bulk-read UPDATE_LOG.md or updates/. When relevant, read only the section "
            "headings of PROJECT_MEMORY.md (e.g. rg -n '^#' <file>) and open matching sections; "
            "migration is described in the chronicle skill (migrate).\n" % listing
        )
    return ""


def _context_args(argv):
    cwd, max_bytes = ".", CONTEXT_MAX_BYTES
    i = 0
    while i < len(argv):
        a = argv[i]
        if a.startswith("--cwd="):
            cwd = a.split("=", 1)[1]
        elif a == "--cwd" and i + 1 < len(argv):
            i += 1
            cwd = argv[i]
        elif a.startswith("--max-bytes="):
            max_bytes = int(a.split("=", 1)[1])
        elif a == "--max-bytes" and i + 1 < len(argv):
            i += 1
            max_bytes = int(argv[i])
        i += 1
    return cwd, max_bytes


def run_context_hook(argv):
    """SessionStart entry point: print the index, or nothing. Never fails, always exit 0."""
    try:
        _utf8_stdio()
        cwd, max_bytes = _context_args(argv)
        root = find_root(cwd) or os.path.abspath(cwd)
        text = context_text(root, max_bytes)
        if text:
            sys.stdout.write(text)
            sys.stdout.flush()
    except BaseException:
        pass
    os._exit(0)


