def _grep_file(path, rx, limit=1000000):
    """Yield (lineno, line) for lines of a text file matching rx."""
    if not os.path.isfile(path):  # also skips FIFOs and devices, which would block
        return
    try:
        if os.path.getsize(path) > limit:
            return
        with open(path, "rb") as f:
            raw = f.read()
    except OSError:
        return
    if b"\x00" in raw[:4096]:
        return
    for n, line in enumerate(raw.decode("utf-8", "replace").splitlines(), 1):
        if rx.search(line):
            yield n, line.strip()


def _clip(s, n=160):
    return s if len(s) <= n else s[: n - 3] + "..."


def _walk_files(top, max_depth=2):
    if not os.path.isdir(top):
        return
    base = top.rstrip(os.sep).count(os.sep)
    for dirpath, dirnames, filenames in os.walk(top):
        if dirpath.count(os.sep) - base >= max_depth:
            dirnames[:] = []
        dirnames.sort()
        for name in sorted(filenames):
            if not name.endswith(".sample"):
                yield os.path.join(dirpath, name)


def _legacy_inventory(root):
    """Return (files, dirs): [(rel, detail)] for legacy memory present in root."""
    files, dirs = [], []
    for rel in LEGACY_FILES:
        full = rpath(root, rel)
        if not os.path.isfile(full):
            continue
        try:
            with open(full, "rb") as f:
                text = f.read().decode("utf-8", "replace")
        except OSError:
            continue
        headings = len(re.findall(r"^## ", text, re.M))
        stamps = len(LAST_UPDATED_RE.findall(text))
        files.append((rel, "%s, %d lines, %d `## ` headings, %d `Last Updated:` lines"
                      % (human_size(len(text.encode("utf-8"))), text.count("\n"), headings, stamps)))
    for rel in LEGACY_DIRS:
        full = rpath(root, rel)
        if not os.path.isdir(full):
            continue
        count = total = 0
        for dirpath, _, filenames in os.walk(full):
            for name in filenames:
                count += 1
                try:
                    total += os.path.getsize(os.path.join(dirpath, name))
                except OSError:
                    pass
        dirs.append((rel + "/", "%d files, %s" % (count, human_size(total))))
    return files, dirs


def _non_memory_docs(root, skip):
    """Files in docs/memory and memory/ that are neither legacy, the index, nor parseable memories."""
    good = set(m.rel for m in scan_store(root)[0] if m.error is None)
    out = []
    for rel_dir in (MEMORY_REL, "memory"):
        full = rpath(root, rel_dir)
        if not os.path.isdir(full):
            continue
        for name in sorted(os.listdir(full)):
            rel = rel_dir + "/" + name
            is_dir = os.path.isdir(os.path.join(full, name))
            if name.startswith(".") or rel == INDEX_REL or rel in good or (rel + "/" if is_dir else rel) in skip:
                continue
            out.append(rel + ("/" if is_dir else ""))
    return out


def _hook_references(root, layout, per_file=5):
    """Return (report lines, files with hits) for hooks and tooling that mention memory."""
    paths, scanned = [], set()
    for top in _hook_dirs(root, layout):
        paths.extend(_walk_files(top))
    claude_dir = rpath(root, ".claude")
    if os.path.isdir(claude_dir):
        paths.extend(os.path.join(claude_dir, f) for f in sorted(os.listdir(claude_dir))
                     if f.startswith("settings") and f.endswith(".json"))
    paths.extend(rpath(root, rel) for rel in HOOK_SCAN_FILES)
    lines, files = [], []
    for path in paths:
        key = os.path.normcase(os.path.realpath(path))
        if key in scanned:
            continue
        scanned.add(key)
        hits = list(_grep_file(path, HOOK_RE))
        if not hits:
            continue
        name = display(root, path)
        files.append(name)
        lines.extend("%s:%d: %s" % (name, n, _clip(t)) for n, t in hits[:per_file])
        if len(hits) > per_file:
            lines.append("%s: ... %d more matching lines" % (name, len(hits) - per_file))
    return lines, files


_CHECK_IGNORE_RE = re.compile(r"^(.*):(\d+):(.*)$")


def _ignore_rules(root, use_git):
    hits = set()
    if use_git:
        _, out = _git(root, "check-ignore", "-v", "--no-index", INDEX_REL, MEMORY_REL + "/chronicle-probe.md")
        for line in out.splitlines():
            m = _CHECK_IGNORE_RE.match(line.partition("\t")[0])
            if m and not m.group(3).startswith("!"):
                hits.add("%s:%s: %s" % (display(root, m.group(1)), m.group(2), m.group(3)))
        return sorted(hits)
    common = _git_layout(root, False)[0]
    exclude = common and os.path.join(common, "info", "exclude")
    rx = re.compile(r"docs/memory|^/?memory/?\*?$|UPDATE_LOG|PROJECT_MEMORY")
    for path in (rpath(root, ".gitignore"), rpath(root, "docs/.gitignore"), exclude):
        if path:
            hits.update("%s:%d: %s" % (display(root, path), n, t)
                        for n, t in _grep_file(path, rx) if not t.startswith("#"))
    return sorted(hits)


