def _line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def _find_email(text):
    for m in EMAIL_RE.finditer(text):
        local, domain = m.group(1).lower(), m.group(2).lower()
        if local in ("git", "noreply", "no-reply") or domain.split(".")[0] in ("example", "users"):
            continue
        return m.start()
    return None


def _find_phone(text):
    for rx in PHONE_RES:
        for m in rx.finditer(text):
            digits = sum(c.isdigit() for c in m.group(0))
            if 9 <= digits <= 15:
                return m.start()
    return None


def lint_memory(m, names, today_date):
    """Findings for one memory file: list of (level, message)."""
    out = []
    err = lambda msg: out.append(("ERROR", msg))  # noqa: E731
    warn = lambda msg: out.append(("WARN", msg))  # noqa: E731
    if m.text is None:
        err(m.error)
        return out
    text = m.text
    for label, rx in SECRET_PATTERNS:
        hit = rx.search(text)
        if hit:
            err("possible secret (%s) at line %d: remove it and rotate the credential" % (label, _line_of(text, hit.start())))
    hit = CONFLICT_RE.search(text)
    if hit:
        err("git conflict marker at line %d" % _line_of(text, hit.start()))
    if not text.lstrip("\ufeff").startswith("---"):
        # A plain document, not a memory: one finding, not a pile of format noise.
        err("missing frontmatter: not a memory file; move it out of docs/memory or rewrite it as entries")
        return out
    if m.size > FILE_ERROR_BYTES:
        err("%d bytes exceeds the %d byte limit: split it into one fact per file" % (m.size, FILE_ERROR_BYTES))
    elif m.size > FILE_WARN_BYTES:
        warn("%d bytes exceeds the %d byte budget: tighten it" % (m.size, FILE_WARN_BYTES))
    hit = LAST_UPDATED_RE.search(text)
    if hit:
        err("`Last Updated:` line at line %d: use the `updated:` field" % _line_of(text, hit.start()))
    for placeholder in TEMPLATE_PLACEHOLDERS:
        if placeholder in text:
            err("unfilled template placeholder `%s`" % placeholder)
            break
    if m.error:
        err(m.error)
    else:
        # Messages name the field and the value's length, never the value: a credential pasted
        # into a field must not be copied into terminal output, agent context or logs.
        meta = m.meta
        missing = [k for k in REQUIRED_KEYS if not meta.get(k)]
        if missing:
            err("missing frontmatter field(s): %s" % ", ".join(missing))
        name = meta.get("name", "")
        if name and not NAME_RE.match(name):
            err("invalid name (%d-char value not shown): use 3-64 chars of a-z, 0-9 and -" % len(name))
        if name and name != m.stem:
            err("name does not match filename: name must equal the filename stem")
        if not NAME_RE.match(m.stem):
            err("invalid filename: use 3-64 chars of a-z, 0-9 and - before .md")
        mtype = meta.get("type", "")
        if mtype and mtype not in TYPES:
            err("invalid type (%d-char value not shown): use one of %s" % (len(mtype), ", ".join(TYPES)))
        if mtype == "status" and not m.stem.startswith("status-"):
            err("status entries must be named status-<branch or topic>")
        updated = meta.get("updated", "")
        updated_date = None
        if updated:
            try:
                if not DATE_RE.match(updated):
                    raise ValueError
                updated_date = datetime.datetime.strptime(updated, "%Y-%m-%d").date()
            except ValueError:
                err("invalid updated date (%d-char value not shown): use YYYY-MM-DD" % len(updated))
        desc = meta.get("description", "")
        if len(desc) > DESCRIPTION_MAX:
            warn("description is %d chars (budget %d)" % (len(desc), DESCRIPTION_MAX))
        if "<!--" in desc or "-->" in desc:
            warn("description contains `<!--` or `-->`: rendered MEMORY.md would hide index lines; reword it")
        for n, key, raw in split_frontmatter(text)[0]:
            if raw and not is_quoted(raw) and _YAML_PLAIN_UNSAFE.search(raw):
                warn("unquoted `%s` at line %d is invalid or truncated YAML (`: `, ` #`, a leading symbol "
                     "or a trailing colon): wrap the value in double quotes" % (key, n))
        if not m.body.strip():
            warn("empty body: state the fact, then **Why:** and **How to apply:**")
        if mtype == "status" and updated_date is not None:
            age = (today_date - updated_date).days
            if age > STATUS_STALE_DAYS:
                warn("status entry not updated for %d days: refresh it, or delete it if the work merged" % age)
        for link in RELATED_RE.findall(m.body):
            if link not in names:
                shown = "[[%s]]" % link if NAME_RE.fullmatch(link) else "(%d-char link not shown)" % len(link)
                warn("related link %s has no matching memory file" % shown)
    pos = _find_email(text)
    if pos is not None:
        warn("email-like string at line %d: no personal data in memory" % _line_of(text, pos))
    pos = _find_phone(text)
    if pos is not None:
        warn("phone-number-like string at line %d: no personal data in memory" % _line_of(text, pos))
    hit = NARRATION_RE.search(text)
    if hit:
        warn("process narration term `%s` at line %d: record the fact, not who or what produced it"
             % (hit.group(1), _line_of(text, hit.start())))
    return out


def lint_store(root):
    """Return (findings, memory_count); findings are (level, path, message)."""
    findings = []
    add = lambda level, path, msg: findings.append((level, path, msg))  # noqa: E731
    memories, others = scan_store(root)
    if not os.path.isdir(rpath(root, MEMORY_REL)):
        add("ERROR", MEMORY_REL, "missing (run chronicle init)")
    else:
        names = set(m.stem for m in memories)
        today_date = today()
        descriptions = {}
        for m in memories:
            for level, msg in lint_memory(m, names, today_date):
                add(level, m.rel, msg)
            desc = " ".join(m.meta.get("description", "").split()).lower()
            if desc:
                if desc in descriptions:
                    add("WARN", m.rel, "same description as %s: merge duplicates" % descriptions[desc])
                else:
                    descriptions[desc] = m.rel
        for rel in others:
            add("WARN", rel, "not a memory file: docs/memory holds only MEMORY.md and <slug>.md memories")
        expected = render_index(memories)
        actual = read_index(root)
        if actual is None:
            add("ERROR", INDEX_REL, "missing or unreadable (run chronicle index)")
        else:
            try:
                size = os.path.getsize(rpath(root, INDEX_REL))
            except OSError:
                size = 0
            if size > INDEX_READ_MAX:
                add("ERROR", INDEX_REL, "%d bytes exceeds the %d byte read limit: session-start context omits "
                    "the entries past it; curate, then run chronicle index" % (size, INDEX_READ_MAX))
            hit = CONFLICT_RE.search(actual)
            if hit:
                add("ERROR", INDEX_REL, "git conflict marker at line %d" % _line_of(actual, hit.start()))
            targets = {}
            for line in actual.splitlines():
                em = ENTRY_LINE_RE.match(line)
                if em:
                    targets[em.group(1)] = targets.get(em.group(1), 0) + 1
            for target in sorted(t for t, n in targets.items() if n > 1):
                add("ERROR", INDEX_REL, "duplicate index lines for %s (%d lines): run chronicle index"
                    % (target, targets[target]))
            if actual != expected:
                exp_lines, act_lines = set(expected.splitlines()), set(actual.splitlines())
                detail = ["%d %s lines" % (n, kind) for n, kind in (
                    (len(exp_lines - act_lines), "missing"), (len(act_lines - exp_lines), "stale")) if n]
                add("ERROR", INDEX_REL, "out of date with the memory files%s: run chronicle index"
                    % (" (%s)" % ", ".join(detail) if detail else ""))
        n_entries = count_entries(expected)
        if n_entries > INDEX_WARN_ENTRIES:
            add("WARN", INDEX_REL, "%d entries (budget %d): curate, merge or delete" % (n_entries, INDEX_WARN_ENTRIES))
        n_bytes = len(expected.encode("utf-8"))
        if n_bytes > INDEX_WARN_BYTES:
            add("WARN", INDEX_REL, "%d bytes (budget %d): session-start context lists the tail by name only; "
                "curate or shorten descriptions" % (n_bytes, INDEX_WARN_BYTES))
    for rel, size in legacy_present(root):
        add("WARN", rel, "legacy memory (%s): migrate per the chronicle skill (references/migrate.md)" % size)
    return findings, sum(1 for m in memories if m.indexable)


