# A home under a WSL drive mount (/mnt/c/Users/...) belongs to Windows.
WSL_DRIVE_RE = re.compile(r"/mnt/[A-Za-z](?:/|$)")


def default_python():
    return "py -3" if os.name == "nt" else "python3"


def hook_command(python, script, windows=None):
    """Hook command line. Forward slashes and double quotes work in bash, PowerShell and cmd alike."""
    if os.name == "nt" if windows is None else windows:
        script = script.replace("\\", "/")
    if " " in python and not python.startswith('"') and os.path.isfile(python):
        python = '"%s"' % python  # an interpreter path with spaces, not "py -3"
    return '%s "%s" context' % (python, script)


# A chronicle handler is a whole command of the shape hook_command writes: a Python interpreter
# (py, python, python3, python3.10, optionally a path, optionally .exe, optionally double-quoted)
# with optional dash flags, a script path ending in skills/chronicle/scripts/chronicle.py, then
# `context` and plain options. A command that merely mentions chronicle, runs something else
# (echo, rm, cat) or chains more shell (; & | < > ` $ or a newline) is the user's and is never taken over.
_HOOK_WORD = r"[^\s\"';&|<>`$()]"
_HOOK_SCRIPT = r"[/\\]skills[/\\]chronicle[/\\]scripts[/\\]chronicle\.py"
_HOOK_INTERP = r"(?:\"(?:[^\"`$\n]*[/\\])?{n}\"|(?:{w}*[/\\])?{n})".format(
    n=r"(?:py|python(?:\d+(?:\.\d+)?)?)(?:\.exe)?", w=_HOOK_WORD)
_CHRONICLE_HOOK_RE = re.compile(
    r"[ \t]*" + _HOOK_INTERP + r"(?:[ \t]+-{w}+)*[ \t]+"
    r"(?:\"[^\"`$\n]*{s}\"|'[^'\n]*{s}'|{w}*{s})"
    r"[ \t]+context(?:[ \t]+{w}+)*[ \t]*".format(w=_HOOK_WORD, s=_HOOK_SCRIPT))


def is_chronicle_handler(handler):
    return isinstance(handler, dict) and bool(_CHRONICLE_HOOK_RE.fullmatch(str(handler.get("command", ""))))


def hook_handler(platform, command):
    handler = {"type": "command", "command": command, "timeout": HOOK_TIMEOUT}
    if platform == "codex":
        handler["additionalContextLimit"] = CODEX_CONTEXT_LIMIT
    return handler


def merge_session_hook(data, handler, matcher):
    """Return a copy of a settings/hooks JSON object with exactly one chronicle SessionStart hook.

    An existing chronicle handler is updated where it is: Codex keys hook trust by group and
    handler position, so moving groups would make it skip the user's other hooks until re-trusted.
    """
    import json

    if not isinstance(data, dict):
        raise ChronicleError("top level is not a JSON object")
    data = json.loads(json.dumps(data))
    hooks = data.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ChronicleError('"hooks" is not a JSON object')
    groups = hooks.get("SessionStart", [])
    if not isinstance(groups, list):
        raise ChronicleError('"hooks.SessionStart" is not a list')
    kept, placed = [], False
    for group in groups:
        if isinstance(group, dict) and isinstance(group.get("hooks"), list) \
                and any(is_chronicle_handler(h) for h in group["hooks"]):
            own_group = all(is_chronicle_handler(h) for h in group["hooks"])
            handlers = []
            for h in group["hooks"]:
                if not is_chronicle_handler(h):
                    handlers.append(h)
                elif not placed:  # update the first one in place (keeping extra keys); drop duplicates
                    updated = dict(h, **handler)
                    for key in HOOK_USER_KEYS:  # the user's own timing and spill settings win
                        if key in h:
                            updated[key] = h[key]
                    handlers.append(updated)
                    placed = True
            if not handlers:
                continue
            group = dict(group, hooks=handlers)
            if own_group:
                group["matcher"] = matcher
        kept.append(group)
    if not placed:
        kept.append({"matcher": matcher, "hooks": [handler]})
    hooks["SessionStart"] = kept
    return data


def apply_hook_file(path, handler, matcher):
    import json
    import shutil

    real = os.path.realpath(path)  # write through a symlink (e.g. into a dotfiles repo), never replace it
    existed = os.path.lexists(path)
    data = {}
    if existed:
        if not os.path.isfile(real):
            raise ChronicleError("%s is not a regular file; left unchanged" % path)
        try:
            with open(real, encoding="utf-8-sig") as f:  # -sig: some Windows editors write a BOM
                raw = f.read()
            data = json.loads(raw) if raw.strip() else {}
        except (OSError, ValueError) as e:
            raise ChronicleError("%s is not readable JSON (%s); left unchanged" % (path, e))
    merged = merge_session_hook(data, handler, matcher)
    if existed and merged == data:
        return "SessionStart hook already present: %s" % path
    note = ""
    backup = path + ".bak-chronicle"
    try:
        if existed:
            if os.path.lexists(backup):  # keep the first backup: it is the pre-chronicle original
                note = " (original kept in %s)" % os.path.basename(backup)
            else:
                shutil.copy2(real, backup)
                note = " (backup: %s)" % os.path.basename(backup)
        else:
            os.makedirs(os.path.dirname(real), exist_ok=True)
        tmp = real + ".tmp-chronicle"
        write_text(tmp, json.dumps(merged, indent=2, ensure_ascii=False) + "\n")
        if existed:
            shutil.copymode(real, tmp)
        os.replace(tmp, real)
    except OSError as e:
        raise ChronicleError("cannot update %s (%s)" % (path, e))
    return "wrote SessionStart hook: %s%s" % (path, note)


def _remove_path(path):
    """Delete a directory tree; a symlink or file is unlinked (a link's target is never touched)."""
    import shutil

    if os.path.isdir(path) and not os.path.islink(path):
        shutil.rmtree(path)
    else:
        os.unlink(path)


def copy_skill(src, dest):
    """Replace dest with a copy of src without ever leaving dest missing or half-written.

    The copy is staged next to dest, the current installation (directory or symlink) is moved
    aside, the staged copy is renamed into place, and only then is the old one deleted. Any
    failure before that restores the old installation.
    """
    import shutil

    if os.path.exists(dest) and os.path.realpath(src) == os.path.realpath(dest):
        return "skill already in place: %s" % dest
    tmp, old = dest + ".tmp-chronicle", dest + ".old-chronicle"
    if os.path.lexists(old):
        raise ChronicleError("%s exists (left by an interrupted install): move it back to %s or delete it, "
                             "then rerun; nothing changed" % (old, dest))
    try:
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        if os.path.lexists(tmp):
            _remove_path(tmp)  # an earlier run's staging copy: chronicle's own files only
        shutil.copytree(src, tmp, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"))
    except OSError as e:  # shutil.Error is an OSError
        if os.path.lexists(tmp):
            shutil.rmtree(tmp, ignore_errors=True)
        raise ChronicleError("cannot stage the skill copy %s (%s); %s left unchanged" % (tmp, e, dest))
    moved = False
    try:
        if os.path.lexists(dest):
            os.replace(dest, old)
            moved = True
        os.replace(tmp, dest)
    except OSError as e:
        if moved:
            try:
                os.replace(old, dest)
            except OSError as e2:
                raise ChronicleError("cannot install %s (%s) nor restore it (%s): the previous installation "
                                     "is in %s; move it back" % (dest, e, e2, old))
        shutil.rmtree(tmp, ignore_errors=True)
        raise ChronicleError("cannot install %s (%s); previous installation left in place" % (dest, e))
    if moved:
        try:
            _remove_path(old)
        except OSError as e:
            return "installed skill: %s (could not delete the previous copy %s: %s; delete it by hand)" % (
                dest, old, e)
    return "installed skill: %s" % dest


def install(home, platforms, hooks, python):
    """Copy the skill and optionally merge SessionStart hooks; returns (lines, ok)."""
    lines, ok = [], True
    if hooks and WSL_DRIVE_RE.match(home):
        lines.append(
            "warning: %s is a Windows drive mounted in WSL: the hook command written there is a Linux "
            "command (%s on a /mnt path) that Windows Claude Code and Codex cannot run. Install from "
            "Windows instead: py -3 <checkout>\\skills\\chronicle\\scripts\\chronicle.py install --hooks"
            % (home, python))
    src = skill_source_dir()
    for platform in platforms:
        dest = os.path.join(home, "." + platform, "skills", "chronicle")
        try:
            lines.append(copy_skill(src, dest))
        except ChronicleError as e:
            lines.append("error: %s" % e)
            ok = False
            continue  # no hook pointing at a skill that is not installed
        if not hooks:
            continue
        script = os.path.join(dest, "scripts", "chronicle.py")
        cfg = os.path.join(home, ".claude", "settings.json") if platform == "claude" \
            else os.path.join(home, ".codex", "hooks.json")
        try:
            handler = hook_handler(platform, hook_command(python, script))
            lines.append(apply_hook_file(cfg, handler, HOOK_MATCHERS[platform]))
        except ChronicleError as e:
            lines.append("error: %s" % e)
            ok = False
    if hooks and "codex" in platforms:
        lines.append("note: Codex runs new or changed hooks only after you review and trust them: run /hooks in Codex.")
    if not hooks:
        lines.append("hint: rerun with --hooks to inject the memory index at session start.")
    return lines, ok


